"""
Prueba unitaria del timeout en el endpoint de detección de patentes.
Verifica que cuando process_image_pipeline supera los 5 segundos,
el endpoint retorna HTTP 408 (Request Timeout) sin depender de
modelos reales (YOLO/PaddleOCR) ni de OpenCV.
"""

import io
import time
from unittest.mock import patch

from fastapi import status
from fastapi.testclient import TestClient

from app.main import app

client = TestClient(app)
DUMMY_TOKEN = "dummy_token"


def test_detect_timeout():
    """
    Mockea process_image_pipeline para que demore >5s y verifica que el
    endpoint retorne 408 con el mensaje de error correspondiente.
    """
    def slow_pipeline(path):
        time.sleep(5.5)
        return [{"plate": "TEST123"}]

    with patch("app.main.process_image_pipeline", side_effect=slow_pipeline):
        img_data = b"\xff\xd8\xff\xe0\x00\x10JFIF\x00\x01\x01\x01\x00H\x00H\x00\x00\xff\xdb\x00C\x00\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xdb\x00C\x01\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\xc0\x00\x11\x08\x00\x01\x00\x01\x03\x01\x22\x00\x02\x11\x01\x03\x11\x01\xff\xc4\x00\x15\x00\x01\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x08\xff\xc4\x00\x14\x10\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\xff\xc4\x00\x15\x01\x01\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x01\xff\xc4\x00\x14\x11\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\xff\xda\x00\x0c\x03\x01\x00\x02\x11\x03\x11\x00\x3f\x00\xd2\x1a\x7f\xff\xd9"

        start = time.time()
        response = client.post(
            "/plate/api/v1/detect",
            files={"file": ("test.jpg", io.BytesIO(img_data), "image/jpeg")},
            headers={"Authorization": f"Bearer {DUMMY_TOKEN}"},
        )
        elapsed = time.time() - start

        assert response.status_code == status.HTTP_408_REQUEST_TIMEOUT
        assert "superó el tiempo límite" in response.json()["detail"]
        assert 5.0 <= elapsed
